# frozen_string_literal: true

bindings_path = Dir.glob(File.expand_path("../target/*/build/ruby-prism-*/out/bindings.rs", __dir__)).max_by { |path| File.mtime(path) }
abort "ruby-prism bindings.rs not found. Run `cargo build` first." unless bindings_path

source = File.read(bindings_path)
functions = source.scan(/^pub fn visit_([a-z_]+)_node<'pr, V>\(visitor: &mut V, node: &(\w+)<'pr>\)\nwhere\n    V: Visit<'pr> \+ \?Sized,\n\{\n(.*?)^\}/m)

arms = functions.map do |snake_name, type_name, body|
  statements = []
  lines = body.lines.map(&:strip).reject(&:empty?)
  index = 0
  while index < lines.length
    line = lines[index]
    case line
    when /\Avisitor\.visit\(&node\.(\w+)\(\)\);\z/
      statements << "children.push(node.#{Regexp.last_match(1)}());"
    when /\Avisitor\.visit_\w+\(&node\.(\w+)\(\)\);\z/
      statements << "children.push(node.#{Regexp.last_match(1)}().as_node());"
    when /\Aif let Some\(node\) = node\.(\w+)\(\) \{\z/
      field = Regexp.last_match(1)
      inner = lines[index + 1]
      conversion = inner.start_with?("visitor.visit(") ? "child" : "child.as_node()"
      statements << "if let Some(child) = node.#{field}() { children.push(#{conversion}); }"
      index += 2
    when /\Afor node in &node\.(\w+)\(\) \{\z/
      field = Regexp.last_match(1)
      inner = lines[index + 1]
      conversion = inner.start_with?("visitor.visit(") ? "child" : "child.as_node()"
      statements << "for child in &node.#{field}() { children.push(#{conversion}); }"
      index += 2
    else
      abort "Unknown statement in visit_#{snake_name}_node: #{line}"
    end
    index += 1
  end

  if statements.empty?
    "        Node::#{type_name} { .. } => {}"
  else
    <<~RUST.chomp
              Node::#{type_name} { .. } => {
                  let node = node.as_#{snake_name}_node().unwrap();
                  #{statements.join("\n            ")}
              }
    RUST
  end
end

output = <<~RUST
  // @generated by tools/generate_child_nodes.rb
  use ruby_prism::Node;

  pub fn child_nodes<'pr>(node: &Node<'pr>) -> Vec<Node<'pr>> {
      let mut children = Vec::new();
      match node {
  #{arms.join("\n")}
          _ => {}
      }
      children
  }
RUST

enum_body = source[/^pub enum Node<'pr> \{\n(.*?)^\}/m, 1]
variant_names = enum_body.scan(/^    (\w+) \{/).flatten
name_arms = variant_names.map { |name| "        Node::#{name} { .. } => \"#{name}\"," }
output << <<~RUST

  pub fn node_type_name(node: &Node<'_>) -> &'static str {
      match node {
  #{name_arms.join("\n")}
      }
  }
RUST

copy_arms = variant_names.map do |name|
  "        Node::#{name} { parser, pointer, marker } => Node::#{name} { parser: *parser, pointer: *pointer, marker: *marker },"
end
output << <<~RUST

  pub fn copy_node<'pr>(node: &Node<'pr>) -> Node<'pr> {
      match node {
  #{copy_arms.join("\n")}
      }
  }
RUST

File.write(File.expand_path("../src/prism/child_nodes.rs", __dir__), output)
puts "Generated #{functions.length} node types"
